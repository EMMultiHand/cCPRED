// Generates app/flutter_service_worker.js with a cache-first strategy.
// Scans the app directory for the warm-up file list.
// Usage: node build_sw.js <appDir>
const fs = require('fs');
const path = require('path');

const appDir = path.resolve(process.argv[2] || 'app');

function walk(dir, base, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = path.posix.join(base, entry.name);
    if (entry.isDirectory()) {
      walk(full, rel, out);
    } else if (entry.isFile()) {
      out.push(rel);
    }
  }
}

const files = [];
walk(appDir, '', files);

// Do not warm the service worker itself; skip huge duplicate engine variants.
const warm = files
  .filter(function (f) {
    if (f === 'flutter_service_worker.js') return false;
    return true;
  })
  .sort();

const sw = `'use strict';

// Cache-first service worker for the local Cyberpunk RED mirror.
// Generated by tools/build_sw.js - do not edit by hand.
const CACHE = 'cpref-mirror-v9';

const CRITICAL = [
  'index.html',
  'flutter_bootstrap.js',
  'main.dart.js',
  'manifest.json',
  'favicon.png',
  'icons/Icon-192.png',
  'icons/Icon-512.png',
];

const WARM = ${JSON.stringify(warm, null, 2)};

self.addEventListener('install', (event) => {
  self.skipWaiting();
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await Promise.all(
        CRITICAL.map((u) => cache.add(u).catch(() => undefined))
      );
    })()
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      try {
        const keys = await caches.keys();
        await Promise.all(
          keys
            .filter((k) => k !== CACHE && k !== 'redcharacters-character-storage-cache-v1')
            .map((k) => caches.delete(k))
        );
      } catch (e) {}
      try {
        await self.clients.claim();
      } catch (e) {}
      warmCache();
    })()
  );
});

let warming = false;

async function fetchFullWithRetries(url) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url, { cache: 'no-store' });
      const buf = await res.arrayBuffer();
      if (!res.ok) return null;
      return new Response(buf, {
        status: res.status,
        statusText: res.statusText,
        headers: res.headers,
      });
    } catch (e) {
      // retry
    }
  }
  return null;
}

async function warmCache() {
  if (warming) return;
  warming = true;
  try {
    const cache = await caches.open(CACHE);
    for (const u of WARM) {
      try {
        const hit = await cache.match(u, { ignoreSearch: true });
        if (hit) continue;
        const res = await fetchFullWithRetries(u);
        if (res) {
          await cache.put(u, res);
        }
      } catch (e) {
        // Network problem or shutdown mid-way: stop for now, resume next time.
        break;
      }
    }
  } catch (e) {}
  warming = false;
}

self.addEventListener('message', (event) => {
  if (event.data === 'warm') {
    warmCache();
  }
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  let url;
  try {
    url = new URL(req.url);
  } catch (e) {
    return;
  }
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const hit = await cache.match(req, { ignoreSearch: true });
      if (hit) return hit;

      // Buffered download with retries: tunnels can abort long responses
      // mid-body; reading the whole body lets us retry cleanly.
      const canBuffer = !req.headers.get('range');
      let lastError = null;
      for (let attempt = 0; attempt < 3; attempt++) {
        try {
          const res = await fetch(req);
          if (!canBuffer) return res;
          const buf = await res.arrayBuffer();
          const copy = new Response(buf, {
            status: res.status,
            statusText: res.statusText,
            headers: res.headers,
          });
          if (res.ok && res.status === 200 && (res.type === 'basic' || res.type === 'default')) {
            cache.put(req, copy.clone()).catch(() => undefined);
          }
          return copy;
        } catch (err) {
          lastError = err;
        }
      }
      if (req.mode === 'navigate') {
        const idx = await cache.match('index.html', { ignoreSearch: true });
        if (idx) return idx;
      }
      console.warn('fetch failed after retries:', req.url, lastError);
      return new Response('offline', { status: 503, statusText: 'offline' });
    })()
  );
});
`;

fs.writeFileSync(path.join(appDir, 'flutter_service_worker.js'), sw, 'utf8');
